/** Pre-render existing vectors; no new artwork. Run with:
 * NODE_PATH=<directory containing sharp> node --import tsx scripts/build-gameplay-icons.ts
 * Like build-branding.cjs, requires sharp (generation only, not the app). */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { ICONS, STAR8 } from '../mobile/src/components/iconPaths';
import { coinGeometry } from '../mobile/src/components/coinGeometry';
import { palette } from '../mobile/src/theme/palette';

const sharp = require('sharp');
const root = resolve(__dirname, '..');
const out = resolve(root, 'mobile/assets/ui-icons');
const hashes: Record<string, string> = {};
const digest = (bytes: Buffer) =>
  createHash('sha256').update(bytes).digest('hex');
mkdirSync(out, { recursive: true });

// The common board controls only. Other sizes, custom strokes and iOS keep SVG.
const names = [
  'back',
  'shuffle',
  'keypad',
  'wheel',
  'hintLetter',
  'hintWord',
  'play',
  'restart',
] as const;

async function raster(
  name: string,
  size: number,
  viewBox: number,
  body: string,
) {
  for (const scale of [1, 2, 3, 4]) {
    const pixels = size * scale;
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${pixels}" height="${pixels}" viewBox="0 0 ${viewBox} ${viewBox}">${body}</svg>`;
    const suffix = scale === 1 ? '' : `@${scale}x`;
    const file = `${name}${suffix}.png`;
    await sharp(Buffer.from(svg)).png().toFile(resolve(out, file));
    hashes[file] = digest(readFileSync(resolve(out, file)));
  }
}

async function main() {
  for (const name of names) {
    const parts: readonly { d: string; fill?: boolean }[] = ICONS[name];
    await raster(
      name,
      32,
      24,
      parts
        .map((part) =>
          part.fill
            ? `<path d="${part.d}" fill="white"/>`
            : `<path d="${part.d}" fill="none" stroke="white" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>`,
        )
        .join(''),
    );
  }
  for (const size of [12, 20]) {
    const g = coinGeometry(size);
    await raster(
      `coin-${size}`,
      size,
      size,
      `<circle cx="${g.r}" cy="${g.r}" r="${g.r}" fill="${palette.goldDeep}"/>` +
        `<circle cx="${g.r}" cy="${g.cy}" r="${g.faceRadius}" fill="${palette.gold}"/>` +
        `<circle cx="${g.r}" cy="${g.cy}" r="${g.ringRadius}" fill="none" stroke="${palette.goldDeep}" stroke-width="${g.strokeWidth}"/>` +
        `<g transform="${g.starTransform}"><path d="${STAR8}" fill="${palette.goldDeep}"/></g>`,
    );
  }
  const assetModule = resolve(
    root,
    'mobile/src/components/gameplayIconAssets.ts',
  );
  const moduleSource = `// Generated by scripts/build-gameplay-icons.ts from the shared vector artwork.
import type { ImageSourcePropType } from 'react-native';
import type { IconName } from './iconPaths';

export const gameplayIconAssets: Partial<Record<IconName, ImageSourcePropType>> = {
${names.map((name) => `  ${name}: require('../../assets/ui-icons/${name}.png'),`).join('\n')}
};
export const gameplayCoinAssets: Partial<Record<number, ImageSourcePropType>> = {
  12: require('../../assets/ui-icons/coin-12.png'),
  20: require('../../assets/ui-icons/coin-20.png'),
};
`;
  writeFileSync(
    assetModule,
    await format(moduleSource, {
      ...(await resolveConfig(assetModule)),
      filepath: assetModule,
    }),
  );
  const sources = Object.fromEntries(
    [
      'mobile/src/components/iconPaths.ts',
      'mobile/src/components/coinGeometry.ts',
      'mobile/src/theme/palette.ts',
      'scripts/build-gameplay-icons.ts',
    ].map((file) => [file, digest(readFileSync(resolve(root, file)))]),
  );
  writeFileSync(
    resolve(out, 'manifest.json'),
    JSON.stringify({ sources, images: hashes }, null, 2) + '\n',
  );
}
void main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
